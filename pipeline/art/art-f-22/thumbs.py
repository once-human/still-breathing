# three value thumbnails (main shapes only): black = tee, grey = mass, light = light
from PIL import Image, ImageDraw
S = 0.25
def T(d, poly, c): d.polygon([(x*S, y*S) for x, y in poly], fill=c)
def E(d, x, y, rx, ry, c): d.ellipse(((x-rx)*S, (y-ry)*S, (x+rx)*S, (y+ry)*S), fill=c)
def L(d, a, b, w, c): d.line([(a[0]*S, a[1]*S), (b[0]*S, b[1]*S)], fill=c, width=max(1, int(w*S)))
ims = []
# A: tunnel of rain trees, show at the end, metro sweeping in from the right, title in the sky opening
im = Image.new('RGB', (300, 400), (21, 21, 21)); d = ImageDraw.Draw(im)
T(d, [(560,560),(640,560),(1180,1480),(20,1480)], (40,40,40))
for x in (560, 600, 640):
    T(d, [(x-6,600),(x+6,600),(x+30,1470),(x-30,1470)], (200,210,220))
for i,(x,y) in enumerate([(120,700),(1080,640),(300,560),(900,560)]):
    T(d, [(x-10,y),(x+10,y),(x+6,1470),(x-6,1470)], (230,160,60))
T(d, [(40,40),(250,60),(330,300),(470,470),(520,560),(340,700),(40,900)], (40,110,70))
T(d, [(1160,40),(960,60),(880,280),(760,440),(690,540),(860,640),(1160,800)], (40,110,70))
T(d, [(40,560),(200,520),(340,560),(340,800),(40,1000)], (110,70,40))
T(d, [(1160,330),(700,430),(700,460),(1160,400)], (180,180,180))
E(d, 590, 520, 130, 70, (235,240,245))
for a in ((590,470),(300,260),(470,250),(760,250),(900,280)):
    L(d, (590,470), a, 14, (235,240,245))
T(d, [(80,1120),(200,1120),(200,1300),(80,1300)], (230,220,200))
T(d, [(300,1050),(450,1050),(450,1170),(300,1170)], (230,200,60))
